@pytest.mark.parametrize(
    "search_string, expected_indices",
    [
        ("пятёроч", [0]),
        ("супермаркеты", [0, 4]),
        ("ТАКСИ", [1, 2]),
        ("аптека", [3]),
        ("интернет", [5]),
        ("связь", [6]),
        ("кинотеатр", []),
    ],
)
def test_search_transactions(
    search_string: str,
    expected_indices: list[int],
) -> None:
    response = search_transactions(TRANSACTIONS, search_string)
    result = json.loads(response)
    expected = [TRANSACTIONS[index] for index in expected_indices]

    assert result == expected


def test_search_transactions_empty_list() -> None:
    response = search_transactions([], "Аптека")
    result = json.loads(response)

    assert result == []


